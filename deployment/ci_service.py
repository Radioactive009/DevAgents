import json
from typing import Dict, Any, Optional

class CIService:
    @staticmethod
    def detect_project_type(files: Dict[str, str]) -> Dict[str, Any]:
        """
        Analyze files to determine framework, language, build command, output directory.
        """
        file_keys = set(files.keys())
        has_pkg = "package.json" in file_keys
        has_py = any(k.endswith(".py") or k == "requirements.txt" for k in file_keys)
        has_html = "index.html" in file_keys or "public/index.html" in file_keys

        pkg_data = {}
        if has_pkg:
            try:
                pkg_data = json.loads(files["package.json"])
            except Exception:
                pass

        deps = {**pkg_data.get("dependencies", {}), **pkg_data.get("devDependencies", {})}
        scripts = pkg_data.get("scripts", {})

        # 1. Next.js
        if "next" in deps or "next.config.js" in file_keys or "next.config.mjs" in file_keys:
            return {
                "type": "nextjs",
                "framework_preset": "nextjs",
                "language": "javascript",
                "build_command": scripts.get("build", "npm run build"),
                "test_command": scripts.get("test", "npm test") if "test" in scripts else None,
                "output_dir": ".next",
                "requires_node": True,
                "requires_python": False
            }

        # 2. Vite
        if "vite" in deps or "vite.config.js" in file_keys or "vite.config.ts" in file_keys:
            return {
                "type": "vite",
                "framework_preset": "vite",
                "language": "javascript",
                "build_command": scripts.get("build", "npm run build"),
                "test_command": scripts.get("test", "npm test") if "test" in scripts else None,
                "output_dir": "dist",
                "requires_node": True,
                "requires_python": False
            }

        # 3. Create React App
        if "react-scripts" in deps:
            return {
                "type": "create-react-app",
                "framework_preset": "create-react-app",
                "language": "javascript",
                "build_command": "npm run build",
                "test_command": "npm test -- --watchAll=false",
                "output_dir": "build",
                "requires_node": True,
                "requires_python": False
            }

        # 4. General Node.js
        if has_pkg:
            return {
                "type": "nodejs",
                "framework_preset": "other",
                "language": "javascript",
                "build_command": scripts.get("build", "npm run build") if "build" in scripts else None,
                "test_command": scripts.get("test", "npm test") if "test" in scripts else None,
                "output_dir": "dist" if "dist" in file_keys else "public",
                "requires_node": True,
                "requires_python": False
            }

        # 5. Python Project
        if has_py:
            return {
                "type": "python",
                "framework_preset": None,  # Not directly Vercel static unless WSGI/Serverless
                "language": "python",
                "build_command": None,
                "test_command": "pytest",
                "output_dir": None,
                "requires_node": False,
                "requires_python": True
            }

        # 6. Static HTML / Vanilla JS
        return {
            "type": "static",
            "framework_preset": None,  # Static files on root
            "language": "html",
            "build_command": None,
            "test_command": "node tests/test_parser.js" if "tests/test_parser.js" in file_keys else None,
            "output_dir": ".",
            "requires_node": any(k.endswith(".js") for k in file_keys),
            "requires_python": False
        }

    @classmethod
    def generate_ci_workflow(cls, files: Dict[str, str], project_name: str = "DevAgents Project") -> str:
        """
        Generate a production-ready, secure GitHub Actions workflow tailored to the project.
        """
        info = cls.detect_project_type(files)
        p_type = info["type"]
        requires_node = info["requires_node"]
        requires_py = info["requires_python"]

        lines = [
            f"# GitHub Actions CI/CD generated by DevAgents for {project_name}",
            "name: CI Pipeline & Quality Gate",
            "",
            "on:",
            "  push:",
            "    branches: [ main ]",
            "  pull_request:",
            "    branches: [ main ]",
            "",
            "permissions:",
            "  contents: read",
            "",
            "jobs:",
            "  validate:",
            "    name: Quality Checks, Tests & Build",
            "    runs-on: ubuntu-latest",
            "    timeout-minutes: 15",
            "    steps:",
            "      - name: Checkout Source Code",
            "        uses: actions/checkout@v4",
            ""
        ]

        # Secret / Credential scanning safety step
        lines.extend([
            "      - name: Verify Secret Exclusion",
            "        run: |",
            "          echo 'Verifying no secrets or .env files were accidentally checked in...'",
            "          if [ -f .env ]; then",
            "            echo '::error::.env file detected in repository root! Rejecting CI.'",
            "            exit 1",
            "          fi",
            "          echo 'Secret audit passed cleanly.'",
            ""
        ])

        # Node setup if required
        if requires_node:
            lines.extend([
                "      - name: Setup Node.js 20",
                "        uses: actions/setup-node@v4",
                "        with:",
                "          node-version: 20",
                "          cache: ${{ hashFiles('package-lock.json') != '' && 'npm' || '' }}",
                ""
            ])
            if "package.json" in files:
                lines.extend([
                    "      - name: Install Node Dependencies",
                    "        run: |",
                    "          if [ -f package-lock.json ]; then",
                    "            npm ci",
                    "          else",
                    "            npm install",
                    "          fi",
                    ""
                ])

        # Python setup if required
        if requires_py:
            lines.extend([
                "      - name: Setup Python 3.11",
                "        uses: actions/setup-python@v5",
                "        with:",
                "          python-version: '3.11'",
                "          cache: ${{ hashFiles('requirements.txt') != '' && 'pip' || '' }}",
                "",
                "      - name: Install Python Dependencies",
                "        run: |",
                "          python -m pip install --upgrade pip pytest",
                "          if [ -f requirements.txt ]; then pip install -r requirements.txt; fi",
                ""
            ])

        # Testing step
        if info.get("test_command"):
            test_cmd = info["test_command"]
            lines.extend([
                "      - name: Run Automated Test Suite",
                f"        run: {test_cmd}",
                ""
            ])
        elif p_type == "static" and "tests/test_parser.js" in files:
            lines.extend([
                "      - name: Run Parser Unit Tests",
                "        run: node tests/test_parser.js",
                ""
            ])

        # Build step
        if info.get("build_command"):
            b_cmd = info["build_command"]
            lines.extend([
                "      - name: Build Application Bundle",
                f"        run: {b_cmd}",
                ""
            ])

        # Static sanity validation if no build step
        if not info.get("build_command") and not info.get("test_command"):
            lines.extend([
                "      - name: Static Verification",
                "        run: |",
                "          echo 'Running static integrity validation...'",
                "          test -f index.html && echo 'HTML entrypoint verified.' || true",
                ""
            ])

        lines.extend([
            "      - name: CI Quality Gate Finalization",
            "        run: echo 'All required checks, tests, and builds passed successfully!'"
        ])

        return "\n".join(lines) + "\n"
